//! Prunes the upstream OpenAPI document down to the surface this mock implements.
//!
//! The full spec is 2.7 MB, which is unreviewable in a diff and pointless to track:
//! the parts we assert against are the Chat, Responses, and model paths plus the
//! schemas they transitively reference. This produces exactly that, so line
//! citations in the plans point at something a fresh clone actually has.

use std::collections::BTreeSet;
use std::path::PathBuf;

use anyhow::{Context, Result};
use clap::Parser;
use serde::Deserialize;
use serde_yaml_ng::{Mapping, Value};

/// Paths the mock implements, and therefore the only ones worth keeping.
const KEEP_PATHS: [&str; 11] = [
    "/chat/completions",
    "/chat/completions/{completion_id}",
    "/chat/completions/{completion_id}/messages",
    "/models",
    "/models/{model}",
    "/responses",
    "/responses/{response_id}",
    "/conversations",
    "/conversations/{conversation_id}",
    "/conversations/{conversation_id}/items",
    "/conversations/{conversation_id}/items/{item_id}",
];

/// Schemas the mock asserts against even though the kept paths do not reference
/// them: upstream's chat paths declare no error responses, but our envelope is
/// checked against `Error`.
const KEEP_SCHEMAS: [&str; 3] = ["Error", "ErrorResponse", "ServiceTier"];

#[derive(Debug, Parser)]
#[command(
    name = "spec_extract",
    about = "Prune the upstream OpenAPI spec to the implemented API surface"
)]
struct Cli {
    #[arg(long, default_value = "openapi.yaml")]
    input: PathBuf,
    #[arg(long, default_value = "docs/spec/chat-completions.openapi.yaml")]
    output: PathBuf,
    #[arg(long, default_value = "openapi.provenance.json")]
    provenance: PathBuf,
}

#[derive(Debug, Deserialize)]
struct Provenance {
    source: String,
    upstream_commit: String,
    sha256: String,
}

fn main() -> Result<()> {
    let cli = Cli::parse();
    let text = std::fs::read_to_string(&cli.input)
        .with_context(|| format!("reading {}", cli.input.display()))?;
    let provenance_text = std::fs::read_to_string(&cli.provenance)
        .with_context(|| format!("reading {}", cli.provenance.display()))?;
    let provenance: Provenance =
        serde_json::from_str(provenance_text.trim_start_matches('\u{feff}'))
            .with_context(|| format!("parsing {}", cli.provenance.display()))?;
    let spec: Value = serde_yaml_ng::from_str(&normalize_i64_bounds(&text))
        .context("parsing the upstream spec")?;

    let extract = prune(&spec)?;
    let rendered = serde_yaml_ng::to_string(&extract)?;
    let header = format!(
        "# Generated by `cargo run --bin spec_extract`. Do not edit.\n\
         # Source: {}\n\
         # Upstream commit: {}\n\
         # Full-spec SHA-256: {}\n\
         # Contains only implemented paths and their transitively referenced schemas.\n",
        provenance.source, provenance.upstream_commit, provenance.sha256,
    );
    if let Some(parent) = cli.output.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(&cli.output, format!("{header}{rendered}"))
        .with_context(|| format!("writing {}", cli.output.display()))?;

    let bytes = std::fs::metadata(&cli.output)?.len();
    println!(
        "wrote {} ({} paths, {} schemas, {:.0} KB)",
        cli.output.display(),
        KEEP_PATHS.len(),
        count_schemas(&extract),
        bytes as f64 / 1024.0
    );
    Ok(())
}

/// Clamps upstream's rounded seed bounds to the valid `i64` range.
///
/// The source writes `+/-9223372036854776000`, apparently rounded through a
/// floating-point representation. Those values neither fit the declared integer
/// type nor parse as a serde YAML integer. The API and reference client use `i64`,
/// so the nearest valid bounds are the faithful executable representation.
fn normalize_i64_bounds(text: &str) -> String {
    text.lines()
        .map(|line| {
            let Some((prefix, value)) = line.rsplit_once(": ") else {
                return line.to_string();
            };
            let trimmed = value.trim();
            let digits = trimmed.strip_prefix('-').unwrap_or(trimmed);
            let is_bound = matches!(
                prefix.split_whitespace().last(),
                Some("minimum" | "maximum")
            );
            if is_bound
                && digits.len() >= 19
                && digits.chars().all(|ch| ch.is_ascii_digit())
                && trimmed.parse::<i64>().is_err()
            {
                let bound = if trimmed.starts_with('-') {
                    i64::MIN
                } else {
                    i64::MAX
                };
                return format!("{prefix}: {bound}");
            }
            line.to_string()
        })
        .collect::<Vec<_>>()
        .join("\n")
}

fn prune(spec: &Value) -> Result<Value> {
    let paths = spec
        .get("paths")
        .and_then(Value::as_mapping)
        .context("spec has no paths")?;
    let schemas = spec
        .get("components")
        .and_then(|components| components.get("schemas"))
        .and_then(Value::as_mapping)
        .context("spec has no components.schemas")?;

    let mut kept_paths = Mapping::new();
    for name in KEEP_PATHS {
        let key = Value::String(name.to_string());
        let entry = paths
            .get(&key)
            .with_context(|| format!("upstream spec no longer has path {name}"))?;
        kept_paths.insert(key, entry.clone());
    }

    let mut wanted: BTreeSet<String> = BTreeSet::new();
    let mut frontier: Vec<Value> = kept_paths.values().cloned().collect();
    for name in KEEP_SCHEMAS {
        if wanted.insert(name.to_string()) {
            let schema = schemas
                .get(Value::String(name.to_string()))
                .with_context(|| format!("upstream spec no longer has schema {name}"))?;
            frontier.push(schema.clone());
        }
    }
    while let Some(value) = frontier.pop() {
        for reference in refs_in(&value) {
            if wanted.insert(reference.clone()) {
                let schema = schemas
                    .get(Value::String(reference.clone()))
                    .with_context(|| format!("reference targets missing schema {reference}"))?;
                frontier.push(schema.clone());
            }
        }
    }

    let mut kept_schemas = Mapping::new();
    for name in &wanted {
        if let Some(schema) = schemas.get(Value::String(name.clone())) {
            kept_schemas.insert(Value::String(name.clone()), schema.clone());
        }
    }

    let mut components = Mapping::new();
    components.insert(
        Value::String("schemas".into()),
        Value::Mapping(kept_schemas),
    );

    let mut root = Mapping::new();
    for key in ["openapi", "info"] {
        if let Some(value) = spec.get(key) {
            root.insert(Value::String(key.into()), value.clone());
        }
    }
    root.insert(Value::String("paths".into()), Value::Mapping(kept_paths));
    root.insert(
        Value::String("components".into()),
        Value::Mapping(components),
    );
    Ok(Value::Mapping(root))
}

/// Collects `#/components/schemas/NAME` targets anywhere inside a value.
fn refs_in(value: &Value) -> Vec<String> {
    let mut found = Vec::new();
    match value {
        Value::Mapping(map) => {
            for (key, entry) in map {
                if key.as_str() == Some("$ref")
                    && let Some(target) = entry.as_str()
                    && let Some(name) = target.strip_prefix("#/components/schemas/")
                {
                    found.push(name.to_string());
                    continue;
                }
                found.extend(refs_in(entry));
            }
        }
        Value::Sequence(items) => {
            for item in items {
                found.extend(refs_in(item));
            }
        }
        _ => {}
    }
    found
}

fn count_schemas(extract: &Value) -> usize {
    extract
        .get("components")
        .and_then(|components| components.get("schemas"))
        .and_then(Value::as_mapping)
        .map(Mapping::len)
        .unwrap_or(0)
}

#[cfg(test)]
mod tests {
    use super::normalize_i64_bounds;

    #[test]
    fn only_oversized_integer_bounds_are_normalized() {
        let source = "minimum: -9223372036854776000\nmaximum: 9223372036854776000\nexample: 9223372036854776000\nminimum: -10";
        assert_eq!(
            normalize_i64_bounds(source),
            "minimum: -9223372036854775808\nmaximum: 9223372036854775807\nexample: 9223372036854776000\nminimum: -10"
        );
    }
}
